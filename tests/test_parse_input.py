"""Every supported export format parses to the same table; wrong builds are refused."""

import pytest

from parse_input import detect, load

ROWS = [("rs1", "1", "100", "AG"), ("rs2", "X", "200", "C"), ("rs3", "Y", "300", "--"), ("rs4", "MT", "400", "T")]


def write_myheritage(p):
    lines = ["# MyHeritage DNA raw data.", "# build 37", "RSID,CHROMOSOME,POSITION,RESULT"]
    lines += [f'"{r}","{c}","{pos}","{gt}"' for r, c, pos, gt in ROWS]
    p.write_text("\n".join(lines) + "\n")


def write_23andme(p):
    lines = ["# This data file generated by 23andMe", "# rsid\tchromosome\tposition\tgenotype"]
    lines += ["\t".join(r) for r in ROWS]
    p.write_text("\n".join(lines) + "\n")


def write_ancestry(p):
    code = {"X": "23", "Y": "24", "MT": "26"}
    lines = ["#AncestryDNA raw data download", "rsid\tchromosome\tposition\tallele1\tallele2"]
    for r, c, pos, gt in ROWS:
        a1, a2 = ("0", "0") if gt == "--" else (gt[0], gt[-1])
        lines.append("\t".join([r, code.get(c, c), pos, a1, a2]))
    p.write_text("\n".join(lines) + "\n")


@pytest.mark.parametrize("writer,fmt", [(write_myheritage, "myheritage"), (write_23andme, "23andme"), (write_ancestry, "ancestrydna")])
def test_formats_agree(tmp_path, writer, fmt):
    f = tmp_path / "raw.txt"
    writer(f)
    assert detect(f) == fmt
    df, got = load(f)
    assert got == fmt
    assert list(df["chrom"]) == ["1", "X", "Y", "MT"]
    assert list(df["pos"]) == [100, 200, 300, 400]
    assert df.loc[0, "gt"] == "AG"
    assert df.loc[1, "gt"] == "CC"  # haploid call doubled
    assert df.loc[2, "gt"] == "--"


def test_grch38_refused(tmp_path):
    f = tmp_path / "raw.csv"
    f.write_text("# MyHeritage DNA raw data. GRCh38\nRSID,CHROMOSOME,POSITION,RESULT\n\"rs1\",\"1\",\"1\",\"AA\"\n")
    with pytest.raises(ValueError, match="GRCh37"):
        load(f)


def test_garbage_calls_become_no_calls(tmp_path):
    f = tmp_path / "raw.csv"
    f.write_text('RSID,CHROMOSOME,POSITION,RESULT\n"rs1","1","1","NN"\n"rs2","1","2","A?"\n"rs3","1","x","AA"\n')
    df, _ = load(f)
    assert list(df["gt"]) == ["--", "--"]  # the unparsable position row is dropped


def test_unknown_format(tmp_path):
    f = tmp_path / "raw.txt"
    f.write_text("hello,world\n")
    with pytest.raises(ValueError, match="unrecognised"):
        detect(f)
